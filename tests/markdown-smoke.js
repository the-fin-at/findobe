async page => {
  const errors=[];
  page.on('pageerror',e=>errors.push(e.message));
  await page.addInitScript(()=>{
    window.initial='\uFEFF# Titel\r\n\r\nEin **fetter** Text.\n\n- Punkt\r\n\r\n| A | B |\n| --- | --- |\n| 1 | 2 |\n';
    window.mockDocument={id:1,name:'note.md',path:'/test/note.md',text:initial};
    window.mockWrites=[];
    window.__TAURI__={core:{invoke:async(cmd,args)=>{
      if(cmd==='open_document')return mockDocument;
      if(cmd==='release_document')return;
      if(cmd==='read_resource')throw 'unavailable';
      if(cmd==='save_document'){if(window.failSave)throw 'Testfehler';mockWrites.push(args);return {name:mockDocument.name,path:mockDocument.path};}
      if(cmd==='export_pdf'){window.printed=args.html;return;}
      if(cmd==='close_editor'){window.didClose=true;return;}
      throw Error(cmd);
    }},event:{listen:async(name,fn)=>{(window.listeners ||= {})[name]=fn;return ()=>{};}}};
  });
  await page.goto('http://127.0.0.1:17893');
  await page.locator('#btnOpen').click();
  const editor=page.locator('#markdownEditor .cm-content');
  const tab=name=>page.locator('#mdViewSwitch').getByRole('button',{name,exact:true});
  await editor.waitFor();
  if(!await page.locator('.md-h1').count())throw Error('Heading not formatted');
  await tab('Quelltext').click();
  if(!await page.locator('.cm-gutters').count()||!await editor.innerText().then(t=>t.includes('# Titel')))throw Error('Missing source syntax');
  await tab('Vorschau').click();
  const preview=page.frameLocator('#markdownPreview');
  await preview.getByRole('heading',{name:'Titel',exact:true}).waitFor();
  if(await preview.locator('strong').innerText()!=='fetter'||await preview.locator('table').count()!==1)throw Error('Markdown preview formatting failed');
  await preview.getByRole('heading',{name:'Titel',exact:true}).click();
  if(await preview.locator('[contenteditable],script').count())throw Error('Preview not read only');
  if(!await page.evaluate(()=>currentContent()===initial&&!isDirty()))throw Error('Mode switches rewrote source');
  await page.locator('#btnSaveAs').click();
  if(!await page.evaluate(()=>mockWrites[0].content===initial&&mockWrites[0].saveAs))throw Error('Exact BOM/mixed EOL save-as failed');
  await tab('Quelltext').click();
  await editor.press('ControlOrMeta+End');
  await page.keyboard.type('abc');
  await page.keyboard.press('Enter');
  await page.keyboard.type('def');
  const grouped=await page.evaluate(()=>currentContent());
  for(let i=0;i<6;i++)await page.keyboard.press('ControlOrMeta+z');
  if(!await page.evaluate(()=>currentContent()===initial))throw Error('Grouped undo diverged from original source');
  for(let i=0;i<6;i++)await page.keyboard.press('ControlOrMeta+Shift+z');
  if(await page.evaluate(()=>currentContent())!==grouped)throw Error('Grouped redo diverged from source');
  for(let i=0;i<6;i++)await page.keyboard.press('ControlOrMeta+z');
  const displayed=await editor.locator('.cm-line').allTextContents();
  if(displayed.join('\n')!==await page.evaluate(()=>mdText.replace(/\r\n|\r/g,'\n')))throw Error('Visible editor and canonical source diverged');
  await tab('Schreiben').click();
  await editor.press('ControlOrMeta+End');
  await page.keyboard.type('## Neu');
  await page.keyboard.press('Enter');
  await page.keyboard.type('Absatz mit **Fett**');
  await page.keyboard.press('Enter');
  await page.keyboard.press('Enter');
  await page.keyboard.type('- Eins');
  await page.keyboard.press('Enter');
  await page.keyboard.type('Zwei');
  if(!await page.evaluate(()=>mdText.includes('- Eins\r\n- Zwei')))throw Error('List continuation failed: '+await page.evaluate(()=>mdText));
  if(!await page.locator('.md-h2').count())throw Error('Typed heading not formatted');
  const changed=await page.evaluate(()=>currentContent());
  await tab('Quelltext').click();
  if(await page.evaluate(()=>currentContent())!==changed)throw Error('Source switch lost edits');
  await tab('Vorschau').click();
  await preview.getByRole('heading',{name:'Neu',exact:true}).waitFor();
  await preview.getByText('Zwei',{exact:true}).waitFor();
  await page.keyboard.press('ControlOrMeta+z');
  if(await page.evaluate(()=>currentContent())!==changed)throw Error('Preview undo modified hidden editor');
  await page.locator('#btnSave').click();
  if(!await page.evaluate(()=>mockWrites.at(-1).content===currentContent()&&!isDirty()))throw Error('Save from preview failed');
  await page.locator('#btnExpPdf').click();
  if(!await page.evaluate(()=>printed.includes('Neu')&&!printed.includes('contenteditable')))throw Error('PDF payload failed');
  await tab('Quelltext').click();
  await editor.press('ControlOrMeta+a');
  await page.keyboard.insertText('# Ersetzt\n\nNeuer Absatz');
  await page.keyboard.press('ControlOrMeta+z');
  if(await page.evaluate(()=>currentContent())!==changed)throw Error('Undo did not preserve mixed EOL source');
  await page.keyboard.press('ControlOrMeta+Shift+z');
  if(!await page.evaluate(()=>mdText.startsWith('# Ersetzt')))throw Error('Redo failed');
  await page.locator('#btnOpen').click();
  await page.locator('#unsavedDialog[open]').waitFor();
  const beforeCancel=await page.evaluate(()=>currentContent());
  await page.keyboard.press('ControlOrMeta+z');
  if(await page.evaluate(()=>currentContent())!==beforeCancel)throw Error('Modal shortcut edited hidden document');
  await page.locator('[data-choice="cancel"]').click();
  if(!await page.evaluate(()=>mdText.startsWith('# Ersetzt')&&isDirty()))throw Error('Cancel lost edits');
  await page.evaluate(()=>{failSave=true;});
  await page.locator('#btnSave').click();
  await page.locator('#errorbar').filter({hasText:'Testfehler'}).waitFor();
  if(!await page.evaluate(()=>isDirty()))throw Error('Failed save cleared dirty');
  await page.evaluate(()=>{failSave=false;});
  await page.locator('#btnSave').click();
  await page.keyboard.press('ControlOrMeta+f');
  await page.locator('.cm-search').waitFor();
  await page.keyboard.press('Escape');
  await page.evaluate(()=>{mockDocument={id:2,name:'empty.md',path:'/test/empty.md',text:''};});
  await page.locator('#btnOpen').click();
  await editor.click();
  await page.keyboard.type('# Neue Datei');
  if(!await page.locator('.md-h1').count())throw Error('Empty document editing failed');
  await page.locator('#btnSave').click();
  await page.evaluate(()=>{mockDocument={id:4,name:'untrusted.md',path:'/test/untrusted.md',text:'# Sicher\n\n<script>window.executed=true;<\/script>\n\n[Link](javascript:alert(1))\n\n<img src="https://example.invalid/x.png" onerror="window.executed=true">'};});
  await page.locator('#btnOpen').click();
  await tab('Vorschau').click();
  await preview.getByRole('heading',{name:'Sicher'}).waitFor();
  if(await preview.locator('script,[onerror],[href^="javascript:"]').count())throw Error('Preview retained active content');
  if(!await page.evaluate(()=>currentContent()===mockDocument.text))throw Error('Sanitizer changed original Markdown');
  await page.evaluate(()=>{mockDocument={id:3,name:'other.html',path:'/test/other.html',text:'<h1>HTML bleibt</h1>'};});
  await page.locator('#btnOpen').click();
  await page.frameLocator('#hviewer').getByRole('heading',{name:'HTML bleibt'}).waitFor();
  if(await page.locator('#markdownWorkspace').isVisible()||await page.locator('#markdownToolbar').isVisible())throw Error('Markdown leaked into HTML');
  if(errors.length)throw Error(errors.join('\n'));
  return {liveHeadings:true,listContinuation:true,threeViews:true,readOnlyPreview:true,exactSourceAndBOM:true,undoRedo:true,saveAsAndPdf:true,unsavedGuard:true,failedSave:true,search:true,emptyFile:true,htmlUnchanged:true,errors};
}
